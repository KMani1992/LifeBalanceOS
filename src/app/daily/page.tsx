  function toggleRecurringTemplate(
    taskTitle: string,
    category: DailyTaskCategory,
    enabled: boolean,
  ) {
    setRecurringTemplates((current) => {
      if (enabled) {
        const exists = current.some(
          (template) =>
            template.title.trim().toLowerCase() ===
            taskTitle.trim().toLowerCase(),
        );
        if (exists) {
          return current;
        }
        return [...current, { title: taskTitle, category }];
      }
      return current.filter(
        (template) =>
          template.title.trim().toLowerCase() !==
          taskTitle.trim().toLowerCase(),
      );
    });
  }

