  /**
   * Loads AI suggestions and caches them for this browser session.
   */
  // Generated by GitHub Copilot
  async function loadSuggestedTasks(forceRefresh = false) {
    if (activeMilestoneGoals.length === 0) {
      setSuggestedTasks([]);
      setSuggestionsError(null);
      return;
    }

    if (!forceRefresh && typeof window !== "undefined") {
      const cached = window.sessionStorage.getItem(suggestionsCacheKey);
      if (cached) {
        try {
          setSuggestedTasks(JSON.parse(cached) as SuggestedTaskItem[]);
          setSuggestionsError(null);
          return;
        } catch {
          window.sessionStorage.removeItem(suggestionsCacheKey);
        }
      }
    }

    try {
      setSuggestionsLoading(true);
      setSuggestionsError(null);

      const response = await fetch("/api/task-suggestions", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          goals: activeMilestoneGoals.map((goal) => ({
            goalId: goal.id,
            title: goal.title,
            category: goal.category,
            subCategory: goal.subCategory ?? null,
          })),
          recentTasks: recentTaskTitles,
          difficultyHint,
        }),
      });

      if (!response.ok) {
        throw new Error(
          `Task suggestions failed with status ${response.status}`,
        );
      }

      const payload = (await response.json()) as SuggestedTaskGroup[];
      const flattened: SuggestedTaskItem[] = [];
      const seen = new Set<string>();

      payload.forEach((group) => {
        const linkedGoal = group.goalId
          ? activeMilestoneGoals.find((goal) => goal.id === group.goalId)
          : activeMilestoneGoals.find((goal) => goal.title === group.goalTitle);

        if (!linkedGoal) {
          return;
        }

        group.suggestions.slice(0, 3).forEach((title) => {
          const normalizedTitle = title.trim();
          const key = `${linkedGoal.id}:${normalizedTitle.toLowerCase()}`;
          if (!normalizedTitle || seen.has(key)) {
            return;
          }
          seen.add(key);
          flattened.push({
            goalId: linkedGoal.id,
            goalTitle: linkedGoal.title,
            title: normalizedTitle,
            category: linkedGoal.category,
          });
        });
      });

      const limited = flattened.slice(0, 5);
      setSuggestedTasks(limited);

      if (typeof window !== "undefined") {
        window.sessionStorage.setItem(
          suggestionsCacheKey,
          JSON.stringify(limited),
        );
      }
    } catch (suggestionsLoadError) {
      setSuggestionsError(
        suggestionsLoadError instanceof Error
          ? suggestionsLoadError.message
          : "Failed to load suggested tasks.",
      );
    } finally {
      setSuggestionsLoading(false);
    }
  }

