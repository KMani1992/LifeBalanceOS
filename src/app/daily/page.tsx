/**
 * Builds small actionable daily suggestions from an active monthly goal title.
 */
// Generated by GitHub Copilot
function buildMonthlyGoalTaskSuggestions(goal: Goal): string[] {
  const normalized = goal.title.toLowerCase();

  if (normalized.includes("react") || normalized.includes("topic")) {
    return ["Watch 1 React video", "Practice 1 concept"];
  }

  if (normalized.includes("budget") || normalized.includes("expense")) {
    return ["Review today expenses for 10 mins", "Update one budget category"];
  }

  if (normalized.includes("sip") || normalized.includes("investment")) {
    return ["Check SIP performance summary", "Read one investment note"];
  }

  if (normalized.includes("saving")) {
    return ["Log today's savings amount", "Compare this week vs last week savings"];
  }

  if (normalized.includes("family") || normalized.includes("kids")) {
    return ["Plan one family activity", "Do one quality family check-in"];
  }

  if (normalized.includes("reflection") || normalized.includes("calm") || normalized.includes("peace")) {
    return ["Do a 10-minute reflection", "Practice 5-minute breathing reset"];
  }

  return [
    `Work 20 mins on ${goal.title}`,
    `Take one small step for ${goal.title}`,
  ];
}

/**
 * Builds a deterministic session cache key for AI suggestions.
 */
// Generated by GitHub Copilot
function buildSuggestionsCacheKey(
  goals: Goal[],
  difficultyHint: "easier" | "balanced" | "advanced",
): string {
  const signature = goals
    .map(
      (goal) =>
        `${goal.id}:${goal.title}:${goal.category}:${goal.subCategory ?? "none"}`,
    )
    .sort()
    .join("|");
  return `${STORAGE_KEYS.taskSuggestionsSession}:${difficultyHint}:${signature}`;
}

function dateOnly(value: string) {
  return value.slice(0, 10);
}

function isTodayTask(task: DailyTask): boolean {
  const today = new Date().toISOString().slice(0, 10);
  const taskDate = task.taskDate ?? dateOnly(task.createdAt);
  return taskDate === today;
}

